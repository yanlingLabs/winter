"""Turn the pinned S1 golden vectors into a C header of byte arrays and expected outcomes.

Run as `python3 -I gen_vectors.py <fixtures dir> <output header>`. Refuses to write anything unless both JSON files
match the SHA-256 pins in PINS.json. The header is a build product (it lives in the build directory, never in git).
"""
import hashlib
import json
import sys
from pathlib import Path


def load(fixtures: Path):
    pins = json.loads((fixtures / "PINS.json").read_text())
    docs = {}
    for name, expected in pins["files"].items():
        data = (fixtures / name).read_bytes()
        actual = hashlib.sha256(data).hexdigest()
        if actual != expected:
            raise SystemExit(f"{name}: sha256 {actual} does not match the pin {expected}")
        docs[name] = json.loads(data)
    return pins, docs


def c_bytes(data: bytes) -> str:
    return ",".join(str(b) for b in data) if data else "0"


def main() -> None:
    fixtures, output = Path(sys.argv[1]), Path(sys.argv[2])
    pins, docs = load(fixtures)
    envelopes, mux = docs["envelopes.json"], docs["mux-frames.json"]
    blind = set(pins["relayBlind"]["vectors"])
    out = ["/* GENERATED by gen_vectors.py from the pinned S1 golden vectors. Never edit, never commit. */\n",
           "#include <stddef.h>\n#include <stdint.h>\n\n",
           "typedef struct { const char *name; int direction; size_t rights; const uint8_t *bytes; size_t length; const char *error; int kind; unsigned seq; } cw_env_vector;\n",
           "typedef struct { const char *name; int direction; const uint8_t *bytes; size_t length; const char *error; int cls; unsigned seq; int blind; } cw_mux_vector;\n\n"]
    env_rows = []
    for index, group in enumerate(("positive", "negative")):
        for number, vector in enumerate(envelopes[group]):
            data = bytes.fromhex(vector["hex"])
            symbol = f"env_{group}_{number}"
            out.append(f"static const uint8_t {symbol}[] = {{{c_bytes(data)}}};\n")
            direction = 0 if vector["direction"] == "to-worker" else 1
            kind = {"scope": 1, "volumes": 2, "drain": 3, "status": 4, "fault": 5}[vector["kind"]] if group == "positive" else 0
            error = "NULL" if group == "positive" else json.dumps(vector["error"])
            seq = vector["seq"] if group == "positive" else 0
            env_rows.append(f'  {{ {json.dumps(vector["name"])}, {direction}, {vector["rights"]}, {symbol}, {len(data)}, {error}, {kind}, {seq} }},\n')
    out.append("static const cw_env_vector env_vectors[] = {\n" + "".join(env_rows) + "};\n")
    out.append(f"#define ENV_VECTOR_COUNT {len(env_rows)}\n#define ENV_POSITIVE_COUNT {len(envelopes['positive'])}\n\n")
    scope = envelopes["scopeDigest"]
    out.append(f"static const char scope_digest_hex[] = {json.dumps(scope['sha256'])};\n\n")

    mux_rows = []
    classes = {"control": 0, "bootstrap": 1, "runtime": 2}
    for group in ("positive", "negative"):
        for number, vector in enumerate(mux[group]):
            data = bytes.fromhex(vector["hex"])
            symbol = f"mux_{group}_{number}"
            out.append(f"static const uint8_t {symbol}[] = {{{c_bytes(data)}}};\n")
            direction = 0 if vector["direction"] == "down" else 1
            positive = group == "positive"
            cls = classes[vector["class"]] if positive else -1
            error = "NULL" if positive else json.dumps(vector["error"])
            seq = vector["seq"] if positive else 0
            is_blind = 1 if (not positive and vector["name"] in blind) else 0
            mux_rows.append(f'  {{ {json.dumps(vector["name"])}, {direction}, {symbol}, {len(data)}, {error}, {cls}, {seq}, {is_blind} }},\n')
    out.append("static const cw_mux_vector mux_vectors[] = {\n" + "".join(mux_rows) + "};\n")
    out.append(f"#define MUX_VECTOR_COUNT {len(mux_rows)}\n#define MUX_POSITIVE_COUNT {len(mux['positive'])}\n")
    missing = blind - {v["name"] for v in mux["negative"]}
    if missing:
        raise SystemExit(f"relayBlind names unknown vectors: {sorted(missing)}")
    output.write_text("".join(out))


if __name__ == "__main__":
    main()

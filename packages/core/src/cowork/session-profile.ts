export interface CoworkToolExposure {
  /** Is an Exa key stored? ABSENT reads as PRESENT, the convention `toolsFor` and the chat prompt keep. */
  exaKeyPresent?: boolean;
  /** Has the user admitted an MCP server? ABSENT reads as none. */
  mcpServers?: boolean;
  /** Is Tool Search on? ABSENT reads as on, as in every Winter mode. */
  toolSearch?: boolean;
}

export interface CoworkToolInputs {
  /** The conversation's current approval policy. */
  approvalPolicy: ApprovalPolicy;
  /** The effective capability ceiling's tool classes (read, write, execute). */
  toolClasses: readonly string[];
  /** The effective capability ceiling's network setting. */
  network: "none" | "internet";
  readonly exposure?: CoworkToolExposure;
  /** Allowlisted names the host removes for this incarnation (a grant, a deliberate omission). */
  readonly withheldTools?: readonly string[];
  /** The readiness keys the host declares built. ABSENT reads as NONE: every row with an unmet need is withheld. */
  readonly readiness?: readonly CoworkReadinessKey[];
}

const POLICIES: readonly ApprovalPolicy[] = ["plan", "dont-ask", "ask", "accept-edits", "auto", "bypass"];
const ALLOWED_NAMES: ReadonlySet<string> = new Set(COWORK_TOOL_ALLOWLIST.map((row) => row.name));

/**
 * The allowlisted names this incarnation is offered, sorted. ONE function: the prompt calls it and the host must
 * build its tool list from it, so the text and the tools cannot disagree. A row is dropped when any of these holds:
 * the host withheld it; a readiness key it needs is not declared; a ceiling class it needs is missing; the policy
 * denies it (or it belongs to another policy); the workspace has no network and it uses the network; its exposure
 * condition is false. Throws CoworkError("invalid_request") on an unknown policy, network, class list, readiness
 * key or withheld name.
 */
export function coworkOfferedTools(input: CoworkToolInputs): string[] {
  if (!POLICIES.includes(input.approvalPolicy) || (input.network !== "none" && input.network !== "internet")) throw new CoworkError("invalid_request");
  if (!Array.isArray(input.toolClasses) || input.toolClasses.some((name) => typeof name !== "string")) throw new CoworkError("invalid_request");
  const withheld = new Set(input.withheldTools ?? []);
  for (const name of withheld) if (!ALLOWED_NAMES.has(name)) throw new CoworkError("invalid_request");
  const ready = new Set<string>(input.readiness ?? []);
  for (const key of ready) if (!Object.hasOwn(COWORK_READINESS, key)) throw new CoworkError("invalid_request");
  const classes = new Set(input.toolClasses), policy = input.approvalPolicy;
  const exa = input.exposure?.exaKeyPresent ?? true, mcp = input.exposure?.mcpServers ?? false, toolSearch = input.exposure?.toolSearch ?? true;
  const admitted = (row: CoworkAllowedTool): boolean => !withheld.has(row.name)
    && (row.needs ?? []).every((key) => ready.has(key))
    && (row.classes ?? []).every((name) => classes.has(name))
    && !(row.deniedUnder ?? []).includes(policy)
    && (row.onlyUnder === undefined || row.onlyUnder.includes(policy))
    && !(input.network === "none" && row.brokers.includes("network"));
  const condition = (row: CoworkAllowedTool): boolean => row.when === undefined ? true
    : row.when === "exa-key" ? exa : row.when === "no-exa-key" ? !exa
    : row.when === "mcp-servers" ? mcp : row.when === "mcp-servers-tool-search-off" ? mcp && !toolSearch : true;
  const offered = new Set(COWORK_TOOL_ALLOWLIST.filter((row) => row.when !== "tool-search-needed" && admitted(row) && condition(row)).map((row) => row.name));
  // ToolSearch exists only when Tool Search is on and something is deferred: an admitted MCP server or a deferred built-in.
  const deferred = mcp || COWORK_TOOL_ALLOWLIST.some((row) => row.deferred === true && offered.has(row.name));
  for (const row of COWORK_TOOL_ALLOWLIST) if (row.when === "tool-search-needed" && admitted(row) && toolSearch && deferred) offered.add(row.name);
  return [...offered].sort();
}


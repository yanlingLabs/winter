/** Display bound for the workspace title. The host accepts up to 200 characters, so a longer title is shortened, never refused. */
export const COWORK_PROMPT_LIMITS = Object.freeze({ maxTitleCharacters: 120 });

export interface CoworkPromptFacts extends CoworkToolInputs {
  /** The workspace title, shown as a sanitised quoted label. Optional (D16); an unusable title is omitted, never an error. */
  readonly workspaceTitle?: string;
  readonly ownership: "standalone" | "project";
  /** This conversation's id: the path segment of its outputs and scratch folders. */
  readonly sessionId: string;
}

/** The segment shape the guest runtime itself requires for a session id (guest-runtime.ts `safeSegment`). */
const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9_.-]{0,127}$/;
const REFUSED_CHARACTER = /[\p{Cc}\p{Cf}\p{Cs}\p{Co}\p{Zl}\p{Zp}\p{Default_Ignorable_Code_Point}]/u;
/** Invisible fillers the general categories miss: CGJ, Hangul fillers, Khmer inherent vowels, braille blank, halfwidth Hangul filler. */
const INVISIBLE_FILLERS: ReadonlySet<number> = new Set([0x034f, 0x115f, 0x1160, 0x17b4, 0x17b5, 0x2800, 0x3164, 0xffa0]);
const BASE_BEFORE_JOINER = /[\p{L}\p{N}\p{M}\p{S}\p{P}]/u;
const BASE_AFTER_JOINER = /[\p{L}\p{N}\p{S}\p{P}]/u;
const BASE_BEFORE_SELECTOR = /[\p{L}\p{N}\p{S}\p{P}\p{Emoji}]/u;
const REPLACEMENT = "�";

const isJoiner = (cp: number) => cp === 0x200c || cp === 0x200d;
const isSelector = (cp: number) => (cp >= 0xfe00 && cp <= 0xfe0f) || (cp >= 0xe0100 && cp <= 0xe01ef) || (cp >= 0x180b && cp <= 0x180d);
const isNoncharacter = (cp: number) => (cp >= 0xfdd0 && cp <= 0xfdef) || (cp & 0xfffe) === 0xfffe;
const refused = (char: string, cp: number) => REFUSED_CHARACTER.test(char) || INVISIBLE_FILLERS.has(cp) || isNoncharacter(cp);

// SETTLED: D16 — owner decision 2026-10-16: the model sees a sanitised workspace title. It is optional; source labels are never shown.
/**
 * A user-chosen title, made safe to show. It is never refused: this runs on every turn, so a title the host
 * accepted must not break generation. NFC; runs of space-like characters collapsed to one space and trimmed;
 * shortened to COWORK_PROMPT_LIMITS characters with an ellipsis; then every control, line-break, bidirectional,
 * tag, zero-width, private-use, surrogate or invisible-filler character is replaced by U+FFFD. A zero-width
 * joiner or non-joiner survives only between two visible characters, and a variation selector only right after
 * a base character, so neither can stand alone or hide at an edge.
 */
function displayTitle(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  let characters = [...(value.length > 4096 ? value.slice(0, 4096) : value).normalize("NFC").replace(/\p{Zs}+/gu, " ").replace(/^ | $/g, "")];
  if (characters.length > COWORK_PROMPT_LIMITS.maxTitleCharacters) characters = [...characters.slice(0, COWORK_PROMPT_LIMITS.maxTitleCharacters - 1), "…"];
  const out: string[] = [];
  characters.forEach((char, index) => {
    const cp = char.codePointAt(0)!;
    const previous = out[out.length - 1];
    if (isJoiner(cp)) {
      const next = characters[index + 1];
      out.push(previous !== undefined && BASE_BEFORE_JOINER.test(previous) && !isJoiner(previous.codePointAt(0)!) && next !== undefined && BASE_AFTER_JOINER.test(next) && !refused(next, next.codePointAt(0)!) ? char : REPLACEMENT);
    } else if (isSelector(cp)) {
      out.push(previous !== undefined && previous !== REPLACEMENT && BASE_BEFORE_SELECTOR.test(previous) && !isSelector(previous.codePointAt(0)!) ? char : REPLACEMENT);
    } else out.push(refused(char, cp) ? REPLACEMENT : char);
  });
  const text = out.join("").replace(/�{2,}/g, REPLACEMENT);
  return text === "" ? undefined : text;
}

function policyLine(policy: ApprovalPolicy, has: (name: string) => boolean): string {
  switch (policy) {
    case "plan":
      return `Plan mode: you can read and research, but you cannot change files or run anything that changes state. The sources and memory are read-only to you, and you have a separate scratch area for planning notes. Work out a plan${has("ExitPlanMode") ? " and present it with ExitPlanMode so the user can approve it" : " and give it to the user"}.`;
    case "dont-ask":
      return "Don't-ask mode: you can do only what is already authorized. Anything that would need a prompt is refused. Do not retry it; tell the user what you needed.";
    case "ask":
      return "Ask mode: the user is asked before edits and other actions, unless something already allows them.";
    case "accept-edits":
      return "Accept-edits mode: edits to files in the workspace go ahead. Other actions ask unless something already allows them.";
    case "auto":
      return `Auto mode: ordinary edits and commands in the workspace go ahead without asking. Some commands can still be refused or asked about${has("Workflow") ? ", and Workflow still asks" : ""}.`;
    case "bypass":
      return "Bypass mode: ordinary prompts are skipped for what the workspace allows. The limits below still hold.";
  }
}

/** The web paragraph, which depends on which search tool this incarnation has (the chat prompt's rule). */

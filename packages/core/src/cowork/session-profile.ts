export interface CoworkAllowedTool {
  /** The name the model sees. */
  readonly name: string;
  readonly runs: CoworkToolRuns;
  readonly brokers: readonly CoworkBroker[];
  /** Offered only while the host reports this condition. Absent: always. */
  readonly when?: CoworkToolCondition;
  /** Every listed class must be in the effective ceiling. Mirrors confinedToolVisibility for the four tools it covers. */
  readonly classes?: readonly CoworkToolClass[];
  /** Readiness keys that must be declared before the tool is offered. */
  readonly needs?: readonly CoworkReadinessKey[];
  /** The tool starts deferred (loaded through ToolSearch), as CronList does in Code. */
  readonly deferred?: true;
  /** Never offered under these policies, because the policy denies it outright. */
  readonly deniedUnder?: readonly ApprovalPolicy[];
  /** Offered only under these policies. */
  readonly onlyUnder?: readonly ApprovalPolicy[];
  /** `spec#<heading>`, `contracts#<heading>`, `protocol#<heading>`, `code#<path>#<symbol>` or `house#<export>`. */
  readonly cite: readonly string[];
  readonly why: string;
  /** The decision this row depends on (`D3`), open or settled. */
  readonly decision?: string;
  /** A name that is NOT in today's tool registry. None today. Must cite the spec section that names it. */
  readonly guestOnly?: { readonly source: string };
}

